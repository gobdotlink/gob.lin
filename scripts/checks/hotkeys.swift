import Foundation

func expect(_ condition: @autoclosure () -> Bool, _ message: String) {
    precondition(condition(), message)
}

var state = HotkeyStateMachine()
state.press(at: 1)
expect(state.release(at: 1.1) == [.beginRecording(.handsFree)], "quick tap starts hands-free")
state.press(at: 2)
expect(state.release(at: 2.1) == [.finishRecording(queueForProcessing: false)], "second tap finishes")
state.press(at: 3)
expect(state.tick(at: 3.31) == [.beginRecording(.hold)], "hold starts even while processing")
expect(state.release(at: 3.5) == [.finishRecording(queueForProcessing: true)], "processing queues without losing a new press")
expect(state.processingCount == 2, "both jobs retained")
state.processingCompleted(); state.processingCompleted()
expect(state.processingCount == 0, "jobs complete independently")
expect(state.press(at: 4) == [.prepareRecording], "a press with nothing recording prepares a take")
expect(state.chord() == [.abandonPreparation], "Cmd+S must not start a Cmd-only recording, and gives back what its press opened")
expect(state.release(at: 4.1).isEmpty, "chord release is ignored")
state.press(at: 5)
expect(state.tick(at: 5.31) == [.beginRecording(.hold)], "hold after chord works")
expect(state.chord() == [.cancelRecording], "adding a chord cancels a pending modifier hold")
expect(state.release(at: 5.5).isEmpty, "cancelled hold does not become a tap")
state.press(at: 6)
expect(state.release(at: 6.1) == [.beginRecording(.handsFree)], "next tap works")
expect(state.cancel() == [.cancelRecording], "Escape cancels recording")
expect(state.cancel().isEmpty, "Escape outside recording has no action")
state.press(at: 7)
state.press(at: 7.05)
expect(state.release(at: 7.32).first == .beginRecording(.hold), "repeat presses cannot replace the initial press")
var boundary = HotkeyStateMachine()
boundary.press(at: 10)
expect(boundary.release(at: 10.29) == [.beginRecording(.handsFree)], "a release just below the threshold remains a tap")
expect(boundary.tick(at: 10.33).isEmpty, "a later queued hold tick cannot change an already released tap")
// Every prepared press ends in exactly one take or one abandon; presses that can't start a take prepare nothing.
var prepare = HotkeyStateMachine()
expect(prepare.press(at: 30) == [.prepareRecording], "a press prepares before tap or hold is known")
expect(prepare.release(at: 30.1) == [.beginRecording(.handsFree)], "a tap begins hands-free with no abandon")
expect(prepare.press(at: 30.5).isEmpty, "the press that ends a hands-free take prepares nothing")
expect(prepare.release(at: 30.6) == [.finishRecording(queueForProcessing: false)], "and still finishes it")
expect(prepare.press(at: 30.65).isEmpty, "a press inside the debounce prepares nothing")
expect(prepare.release(at: 30.7).isEmpty, "and its release does nothing")
expect(prepare.press(at: 31) == [.prepareRecording], "a hold prepares")
expect(prepare.press(at: 31.1).isEmpty, "a repeat press prepares nothing more")
expect(prepare.tick(at: 31.31) == [.beginRecording(.hold)], "then begins at the threshold")
expect(prepare.chord() == [.cancelRecording], "a chord after the threshold cancels the take, not the preparation")
expect(prepare.release(at: 31.5).isEmpty, "and its release does nothing")
expect(prepare.press(at: 32) == [.prepareRecording] && prepare.cancel() == [.abandonPreparation], "Escape before the threshold abandons")
expect(prepare.cancel().isEmpty && prepare.tick(at: 32.4).isEmpty, "an abandoned press abandons once and never begins")
expect(prepare.press(at: 33) == [.prepareRecording] && prepare.release(at: 33.4) == [.beginRecording(.hold), .finishRecording(queueForProcessing: true)],
       "a late release keeps the hold's start and stop")
checkShortcuts()
print("Hotkey safety checks passed")
